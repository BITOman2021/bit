type Leaf = readonly [string, string];
type Tree = { readonly [k: string]: Leaf | Tree };
type Resolve<T> = T extends Leaf ? string : { [K in keyof T]: Resolve<T[K]> };

function pick<T extends Tree>(t: T, i: 0 | 1): Resolve<T> {
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(t)) out[k] = Array.isArray(v) ? v[i] : pick(v as Tree, i);
  return out as Resolve<T>;
}

export type Locale = "ar" | "en";
export type Dict = Resolve<typeof D>;
const cache: Partial<Record<Locale, Dict>> = {};

export function getDict(locale: Locale): Dict {
  return (cache[locale] ??= pick(D as unknown as Tree, locale === "ar" ? 0 : 1) as Dict);
}

/** تسمية قيمة enum */
export function label(t: Dict, group: keyof Dict["enums"], value: string | null | undefined): string {
  if (!value) return "—";
  const g = t.enums[group] as Record<string, string>;
  return g[value] ?? value;
}

export const dir = (l: Locale) => (l === "ar" ? "rtl" : "ltr");
